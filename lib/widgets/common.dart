/// Pilihan kebiasaan yang sedang dipantau.
class HabitSelector extends StatelessWidget {
  const HabitSelector({super.key});

  @override
  Widget build(BuildContext context) {
    final vm = context.watch<SessionViewModel>();
    return Wrap(
      spacing: 8,
      runSpacing: 8,
      children: [
        for (final h in vm.habits)
          ChoiceChip(
            avatar: Icon(h.icon, size: 18),
            label: Text(h.name),
            showCheckmark: false,
            selected: vm.selectedHabitId == h.id,
            onSelected: (_) => vm.selectHabit(h.id),
          ),
      ],
    );
  }
}

void showAppSnack(BuildContext context, String message, {bool error = false}) {
  final cs = Theme.of(context).colorScheme;
  ScaffoldMessenger.of(context)
    ..hideCurrentSnackBar()
    ..showSnackBar(
      SnackBar(
        content: Text(
          message,
          style: TextStyle(color: error ? cs.onError : null),
        ),
        backgroundColor: error ? cs.error : null,
        behavior: SnackBarBehavior.floating,
      ),
    );
}

Future<bool> confirmDialog(
  BuildContext context, {
  required String title,
  required String message,
  String confirmLabel = 'Ya',
  String cancelLabel = 'Batal',
}) async {
  final result = await showDialog<bool>(
    context: context,
    builder: (ctx) => AlertDialog(
      title: Text(title),
      content: Text(message),
      actions: [
        TextButton(
          onPressed: () => Navigator.of(ctx).pop(false),
          child: Text(cancelLabel),
        ),
        FilledButton(
          onPressed: () => Navigator.of(ctx).pop(true),
          child: Text(confirmLabel),
        ),
      ],
    ),
  );
  return result ?? false;
}
